// Generate Quran URL for a page number
function getQuranUrl(page) {
  const mapping = PAGE_TO_AYAH[page];
  if (!mapping) {
    // Default to page 1 if invalid
    return `https://quran.ksu.edu.sa/index.php#aya=1_1&m=hafs&qaree=husary&trans=ar_mu`;
  }
  return `https://quran.ksu.edu.sa/index.php#aya=${mapping.surah}_${mapping.ayah}&m=hafs&qaree=husary&trans=ar_mu`;
}

// Get the surah that a page belongs to (primary surah on that page)
function getPageSurah(page) {
  const mapping = PAGE_TO_AYAH[page];
  return mapping ? mapping.surah : 1;
}
